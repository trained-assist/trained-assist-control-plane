-- 0010_backfill_start_deadline.sql
-- Миграционная политика для строк, созданных ДО 0008.
--
-- Проблема: колонка durable_tasks.start_deadline_at появилась миграцией 0008 и
-- заполняется только при приёме. Задачи, принятые раньше, в pre-start стадиях
-- ('collecting','preparing','queued','handing_off') остались с NULL — а детектор
-- `sweepStuckAccepted` выбирает `start_deadline_at IS NOT NULL`, то есть они
-- ВЫПАЛИ из наблюдения: watchdog их никогда не увидит.
--
-- Политика: дедлайн назначается от updated_at (момент последнего фактического
-- движения по задаче), а не от now(). Возраст отражает реальное ожидание, а не
-- искусственную задержку дедлона после бэкапа. Задачи, ждавшие дольше
-- стандартной границы, сразу попадут в следующий проход детектора — это
-- намеренно: тихий вход опаснее ложного срабатывания.
--
-- Чего НЕ делаем:
--   • не выдумываем дедлайн для задач вне pre-start (running/terminal) — там он
--     неприменим;
--   • не удаляем и не переписываем такие задачи;
--   • не отмечаем их заранее заалерченными: если вход действительно завис,
--     оператор должен узнать об этом на первом же проходе.

UPDATE durable_tasks
   SET start_deadline_at = updated_at + 600000
 WHERE start_deadline_at IS NULL
   AND stage IN ('collecting','preparing','queued','handing_off');